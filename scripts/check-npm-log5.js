const fs = require('fs');
const { execSync } = require('child_process');
const log = execSync('gh run view 45088276176 --log', { encoding: 'utf8', maxBuffer: 10 * 1024 * 1024 });
const lines = log.split(/\r?\n/);
const errors = lines.filter((l) => /npm error/i.test(l));
console.log('npm errors:', errors.length);
errors.forEach((l) => console.log(l.slice(0, 300)));
const steps = lines.filter((l) => /##\[group\]Run /i.test(l));
console.log('\nSteps:', steps.length);
steps.forEach((s) => console.log(s.slice(0, 100)));
const publishLines = lines.filter((l) => l.includes('+ aegisai-harness@'));
console.log('\npublish output:', publishLines.length);
publishLines.forEach((l) => console.log(l.slice(0, 100)));
