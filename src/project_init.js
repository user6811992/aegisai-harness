// src/project_init.js
// Project initialization: auto-generate MCP configs, repo instructions, memory files,
// test commands, and validation scripts for any coding agent. Inspired by harnessforge.
const fs = require('fs');
const path = require('path');

function detectProjectType(root) {
  const files = fs.readdirSync(root);
  const has = (f) => files.includes(f);
  const hasExt = (ext) => files.some((f) => f.endsWith(ext));
  if (has('package.json')) return 'node';
  if (has('pyproject.toml') || has('setup.py') || has('requirements.txt')) return 'python';
  if (has('Cargo.toml')) return 'rust';
  if (has('go.mod')) return 'go';
  if (has('pom.xml') || has('build.gradle')) return 'java';
  if (hasExt('.csproj') || hasExt('.sln')) return 'dotnet';
  return 'generic';
}

function getTestCommand(type) {
  switch (type) {
    case 'node': return 'npm test';
    case 'python': return 'pytest';
    case 'rust': return 'cargo test';
    case 'go': return 'go test ./...';
    case 'java': return 'mvn test';
    case 'dotnet': return 'dotnet test';
    default: return 'echo "no test command configured"';
  }
}

function getLintCommand(type) {
  switch (type) {
    case 'node': return 'npm run lint';
    case 'python': return 'ruff check .';
    case 'rust': return 'cargo clippy';
    case 'go': return 'golangci-lint run';
    default: return null;
  }
}

function generateAgentsMd(root, type, testCmd) {
  return `# AGENTS.md — Project Agent Guide

## Project Type
${type}

## Test Command
\`${testCmd}\`

## Agent Instructions
- Run tests before claiming completion.
- Keep changes minimal and focused.
- Update documentation when code changes.
- Follow existing code style and patterns.

## Verification
Before claiming work is complete:
1. Run the test command and confirm all tests pass.
2. Review the diff for correctness and security.
3. Update relevant documentation.

Generated by aegisai-harness init.
`;
}

function generateMcpConfig(root, type) {
  const config = {
    mcpServers: {},
  };
  // Add common MCP servers based on project type
  if (type === 'node') {
    config.mcpServers.filesystem = { command: 'npx', args: ['-y', '@modelcontextprotocol/server-filesystem', root] };
  }
  if (type === 'python') {
    config.mcpServers.filesystem = { command: 'npx', args: ['-y', '@modelcontextprotocol/server-filesystem', root] };
  }
  return JSON.stringify(config, null, 2);
}

function initProject(root) {
  root = root || process.cwd();
  const type = detectProjectType(root);
  const testCmd = getTestCommand(type);
  const lintCmd = getLintCommand(type);

  const created = [];
  const skipped = [];

  // 1. AGENTS.md
  const agentsPath = path.join(root, 'AGENTS.md');
  if (!fs.existsSync(agentsPath)) {
    fs.writeFileSync(agentsPath, generateAgentsMd(root, type, testCmd));
    created.push('AGENTS.md');
  } else {
    skipped.push('AGENTS.md (already exists)');
  }

  // 2. .mcp.json (MCP server config)
  const mcpPath = path.join(root, '.mcp.json');
  if (!fs.existsSync(mcpPath)) {
    fs.writeFileSync(mcpPath, generateMcpConfig(root, type));
    created.push('.mcp.json');
  } else {
    skipped.push('.mcp.json (already exists)');
  }

  // 3. .aegisai/ directory with project config
  const aegisDir = path.join(root, '.aegisai');
  if (!fs.existsSync(aegisDir)) {
    fs.mkdirSync(aegisDir, { recursive: true });
    const projectConfig = {
      type,
      testCommand: testCmd,
      lintCommand: lintCmd,
      initialized: new Date().toISOString(),
      version: require('./version').VERSION,
    };
    fs.writeFileSync(path.join(aegisDir, 'project.json'), JSON.stringify(projectConfig, null, 2));
    created.push('.aegisai/project.json');
  } else {
    skipped.push('.aegisai/ (already exists)');
  }

  // 4. .gitignore additions
  const gitignorePath = path.join(root, '.gitignore');
  const aegisIgnore = '\n# AegisAi Harness\n.aegisai/\n';
  if (fs.existsSync(gitignorePath)) {
    const content = fs.readFileSync(gitignorePath, 'utf8');
    if (!content.includes('.aegisai/')) {
      fs.appendFileSync(gitignorePath, aegisIgnore);
      created.push('.gitignore (updated)');
    }
  } else {
    fs.writeFileSync(gitignorePath, aegisIgnore.trim() + '\n');
    created.push('.gitignore');
  }

  return {
    ok: true,
    projectType: type,
    testCommand: testCmd,
    lintCommand: lintCmd,
    created,
    skipped,
    root,
  };
}

module.exports = { detectProjectType, getTestCommand, getLintCommand, generateAgentsMd, generateMcpConfig, initProject };