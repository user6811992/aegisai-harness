function initProject(root) {
  root = root || process.cwd();
  const type = detectProjectType(root);
  const testCmd = getTestCommand(type);
  const lintCmd = getLintCommand(type);

  const created = [];
  const skipped = [];

  // 1. AGENTS.md
  const agentsPath = path.join(root, 'AGENTS.md');
  if (!fs.existsSync(agentsPath)) {
    fs.writeFileSync(agentsPath, generateAgentsMd(root, type, testCmd));
    created.push('AGENTS.md');
  } else {
    skipped.push('AGENTS.md (already exists)');
  }

  // 2. .mcp.json (MCP server config)
  const mcpPath = path.join(root, '.mcp.json');
  if (!fs.existsSync(mcpPath)) {
    fs.writeFileSync(mcpPath, generateMcpConfig(root, type));
    created.push('.mcp.json');
  } else {
    skipped.push('.mcp.json (already exists)');
  }

  // 3. .aegisai/ directory with project config
  const aegisDir = path.join(root, '.aegisai');
  if (!fs.existsSync(aegisDir)) {
    fs.mkdirSync(aegisDir, { recursive: true });
    const projectConfig = {
      type,
      testCommand: testCmd,
      lintCommand: lintCmd,
      initialized: new Date().toISOString(),
      version: require('./version').VERSION,
    };
    fs.writeFileSync(path.join(aegisDir, 'project.json'), JSON.stringify(projectConfig, null, 2));
    created.push('.aegisai/project.json');
  } else {
    skipped.push('.aegisai/ (already exists)');
  }

  // 4. .gitignore additions
  const gitignorePath = path.join(root, '.gitignore');
  const aegisIgnore = '\n# AegisAi Harness\n.aegisai/\n';
  if (fs.existsSync(gitignorePath)) {
    const content = fs.readFileSync(gitignorePath, 'utf8');
    if (!content.includes('.aegisai/')) {
      fs.appendFileSync(gitignorePath, aegisIgnore);
      created.push('.gitignore (updated)');
    }
  } else {
    fs.writeFileSync(gitignorePath, aegisIgnore.trim() + '\n');
    created.push('.gitignore');
  }

  // 5. SOUL.md - System Architecture Overview
  const soulPath = path.join(root, 'SOUL.md');
  if (!fs.existsSync(soulPath)) {
    fs.writeFileSync(soulPath, generateSoulMd(type));
    created.push('SOUL.md');
  } else {
    skipped.push('SOUL.md (already exists)');
  }

  // 6. TOOLS.md - Tool Catalog
  const toolsPath = path.join(root, 'TOOLS.md');
  if (!fs.existsSync(toolsPath)) {
    fs.writeFileSync(toolsPath, generateToolsMd(type));
    created.push('TOOLS.md');
  } else {
    skipped.push('TOOLS.md (already exists)');
  }

  // 7. MEMORY.md - Memory Hierarchy
  const memoryPath = path.join(root, 'MEMORY.md');
  if (!fs.existsSync(memoryPath)) {
    fs.writeFileSync(memoryPath, generateMemoryMd(type));
    created.push('MEMORY.md');
  } else {
    skipped.push('MEMORY.md (already exists)');
  }

  // 8. Forbidden Path Rules
  const rulesPath = path.join(root, 'PATH_RULES.md');
  if (!fs.existsSync(rulesPath)) {
    fs.writeFileSync(rulesPath, generateForbiddenPathRules(type));
    created.push('PATH_RULES.md');
  } else {
    skipped.push('PATH_RULES.md (already exists)');
  }

  // 9. MCP Recommendations
  const mcpRecs = generateMcpRecommendations(type);
  const mcpRecsPath = path.join(root, 'MCP_RECOMMENDATIONS.json');
  if (!fs.existsSync(mcpRecsPath)) {
    fs.writeFileSync(mcpRecsPath, JSON.stringify(mcpRecs, null, 2));
    created.push('MCP_RECOMMENDATIONS.json');
  } else {
    skipped.push('MCP_RECOMMENDATIONS.json (already exists)');
  }

  return {
    ok: true,
    projectType: type,
    testCommand: testCmd,
    lintCommand: lintCmd,
    created,
    skipped,
    root,
  };
}

