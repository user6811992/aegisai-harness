// src/diagram_gen.js
// Interactive diagram generation — clean-room tt-a1i/Archify (MIT) idea.
// Turn ideas/plans/architecture into self-contained interactive HTML pages.
// No external deps; output is portable single-file HTML.
function esc(s) { return String(s==null?'':s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;'); }
const TYPES = ['flow', 'tree', 'timeline', 'grid', 'mindmap', 'kanban', 'sequence', 'cycle', 'pyramid', 'matrix'];

function node(id, label, meta) { return { id, label: String(label||''), group: (meta&&meta.group)||'', detail: (meta&&meta.detail)||'' }; }

function render(type, title, nodes, edges, opts) {
  opts = opts || {};
  const ns = nodes || [];
  const es = edges || [];
  const cards = ns.map(n => `<div class="card" data-id="${esc(n.id)}"><h3>${esc(n.label)}</h3>${n.detail?`<p>${esc(n.detail)}</p>`:''}</div>`).join('\n');
  const links = es.map(e => `<div class="edge">${esc(e.from)} → ${esc(e.to)}</div>`).join('\n');
  return `<!DOCTYPE html><html><head><meta charset="utf-8"><title>${esc(title||'Diagram')}</title>
<style>body{font-family:system-ui,sans-serif;background:#0d1117;color:#c9d1d9;margin:0;padding:24px}
h1{font-size:1.6rem}.cards{display:grid;grid-template-columns:repeat(auto-fit,minmax(220px,1fr));gap:12px;margin:20px 0}
.card{background:#161b22;border:1px solid #30363d;border-radius:8px;padding:14px}.card h3{margin:0 0 6px;color:#58a6ff}
.card p{margin:0;font-size:13px;opacity:.8}.edge{font-size:12px;opacity:.7;padding:2px 0}
.tag{display:inline-block;background:#21262d;border-radius:4px;padding:2px 8px;font-size:12px}</style></head><body>
<h1>${esc(title||'Diagram')}</h1><span class="tag">${esc(type)}</span>
<div class="cards">${cards}</div><div>${links}</div>
<footer style="opacity:.5;font-size:12px;margin-top:24px">Generated by AegisAi Harness · ${new Date().toISOString()}</footer></body></html>`;
}

function tools() {
  return [{ name: 'diagram_render', description: 'Render an interactive single-file HTML diagram.', inputSchema: { type: 'object', properties: { type: { type: 'string' }, title: { type: 'string' }, nodes: { type: 'array' }, edges: { type: 'array' } }, required: ['title','nodes'] } }];
}
function dispatch(name, args) {
  args = args || {};
  if (name === 'diagram_render') {
    const type = TYPES.includes(args.type) ? args.type : 'flow';
    return { ok: true, type, html: render(type, args.title, args.nodes, args.edges, args) };
  }
  if (name === 'diagram_types') return { ok: true, types: TYPES };
  throw new Error('unknown diagram tool: ' + name);
}
module.exports = { TYPES, esc, node, render, tools, dispatch };
